"""Discover a local runtime and register ComfyFlash with a shell-capable agent."""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
from tempfile import NamedTemporaryFile

ROOT = Path(__file__).resolve().parents[1]
if not __package__:
    sys.path.insert(0, str(ROOT))

from engine import Flash
from engine.core import DEFAULT_CONFIG, load_config

ENTRY = Path(__file__).resolve()
GUIDE = ENTRY.parent / "skills" / "comfyflash" / "SKILL.md"
MANAGED = "<!-- generated by ComfyFlash register -->"
SKILLS = {"codex": ".agents", "claude-code": ".claude"}
LIBRARIES = ("torch", "PIL", "numpy", "av", "safetensors", "comfy_aimdo", "comfy_kitchen")


def read_json(path):
    with path.open(encoding="utf-8-sig") as stream:
        obj = json.load(stream)
    if not isinstance(obj, dict):
        raise ValueError(f"JSON 需要一个对象 | {path}")
    return obj


def json_text(value):
    return json.dumps(value, ensure_ascii=False, indent=2) + "\n"


def write_text(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with NamedTemporaryFile(mode="w", encoding="utf-8", dir=path.parent, delete=False) as stream:
        temp = Path(stream.name)
        stream.write(text)
    try:
        temp.replace(path)
    finally:
        temp.unlink(missing_ok=True)


def find_comfyui(explicit):
    if explicit:
        candidates = [Path(explicit).expanduser().resolve()]
    else:
        parents = {ROOT.parent, Path.cwd(), Path(sys.executable).resolve().parent.parent}
        candidates = []
        for parent in parents:
            candidates.extend((parent, parent / "ComfyUI"))
            candidates.extend(folder / "ComfyUI" for folder in parent.glob("ComfyUI*"))
    found = {p.resolve() for p in candidates if (p / "comfy" / "sd.py").is_file()}
    if len(found) == 1:
        return found.pop()
    if found:
        roots = ", ".join(sorted(map(str, found)))
        raise ValueError(f"发现多个 ComfyUI 安装 | {roots}。用 --comfyui-root 指定一个。")
    raise ValueError("找不到 ComfyUI 推理目录。用 --comfyui-root 指向含 comfy/sd.py 的目录。")


def configure(args):
    path = args.config.expanduser().resolve()
    exists = path.is_file()
    config = read_json(path) if exists else {"device": "cuda:0"}
    if args.comfyui_root or not exists:
        root = find_comfyui(args.comfyui_root or os.getenv("COMFYUI_ROOT"))
        config["comfyui_root"] = str(root)
    if args.models_path:
        config["comfyui_models_path"] = str(Path(args.models_path).expanduser().resolve())
    if not exists or args.comfyui_root or args.models_path:
        write_text(path, json_text(config))
    return path


def choose_python(comfy, requested):
    if requested:
        candidates = [shutil.which(requested) or requested]
    else:
        portable = comfy.parent / "python_embeded" / "python.exe"
        venv = Path("Scripts/python.exe") if sys.platform == "win32" else Path("bin/python")
        candidates = [portable]
        candidates.extend(folder / name / venv for folder in (comfy, comfy.parent) for name in (".venv", "venv"))
        candidates.append(sys.executable)
    probe = (
        "import importlib.util as u, json, sys;"
        "print(json.dumps([m for m in sys.argv[1:] if u.find_spec(m) is None]));"
        "sys.exit(0 if sys.version_info >= (3, 10) else 1)"
    )
    failures = []
    for item in dict.fromkeys(candidates):
        path = Path(item).expanduser().absolute()
        if not path.is_file():
            continue
        try:
            run = subprocess.run(
                [str(path), "-B", "-c", probe, *LIBRARIES],
                capture_output=True, text=True, timeout=15,
            )
            missing = json.loads(run.stdout.strip()) if run.returncode == 0 else ["Python 3.10+"]
        except (OSError, ValueError, subprocess.TimeoutExpired):
            failures.append(f"{path} (探测失败)")
            continue
        if not missing:
            return path
        failures.append(f"{path} ({', '.join(missing)})")
    details = "；".join(failures)
    raise ValueError(f"找不到可用的推理 Python。用 --python 指定已安装 ComfyUI 推理依赖的解释器。{details}")


def project_skill(args):
    if args.project is None:
        return None
    project = args.project.expanduser().resolve()
    if not project.is_dir():
        raise ValueError(f"找不到项目目录 | {project}")
    path = project / SKILLS[args.agent] / "skills" / "comfyflash" / "SKILL.md"
    if not path.resolve().is_relative_to(project):
        raise ValueError(f"项目技能目录指向项目外 | {path}")
    if path.exists() and MANAGED not in path.read_text(encoding="utf-8-sig").splitlines():
        raise FileExistsError(f"项目已有自定义 ComfyFlash 技能 | {path}")
    return path


def exclude_skill_from_git(project, skill):
    """Keep generated machine paths out of Git without editing tracked files."""
    git = shutil.which("git")
    git_here = any((parent / ".git").exists() for parent in (project, *project.parents))
    if not git:
        if git_here:
            raise ValueError("需要 Git 来保护本机注册文件。当前对话仍可直接注册。")
        return

    def query(*args):
        return subprocess.run(
            [git, "-C", str(project), *args],
            capture_output=True, encoding="utf-8", errors="replace", timeout=10,
        )

    root = query("rev-parse", "--show-toplevel")
    if root.returncode:
        if git_here:
            raise ValueError(f"无法读取目标 Git 仓库 | {project}")
        return

    path = skill.relative_to(project).as_posix()
    if query("check-ignore", "-q", "--", path).returncode == 0:
        return
    if query("ls-files", "--error-unmatch", "--", path).returncode == 0:
        raise ValueError(f"项目已跟踪技能路径，请为本机注册保留未跟踪的技能路径 | {skill}")
    info = query("rev-parse", "--path-format=absolute", "--git-path", "info/exclude")
    info.check_returncode()
    exclude = Path(info.stdout.strip())
    exclude.parent.mkdir(parents=True, exist_ok=True)
    rule = skill.relative_to(Path(root.stdout.strip()).resolve()).as_posix()
    for character in ("[", "*", "?"):
        rule = rule.replace(character, "\\" + character)
    with exclude.open("ab") as stream:
        stream.write(f"\n/{rule}\n".encode("utf-8"))
    if query("check-ignore", "-q", "--", path).returncode:
        raise ValueError(f"项目 Git 规则覆盖了本机忽略设置 | {skill}")


def register(args):
    skill = project_skill(args)
    config = configure(args)
    cfg = load_config(config)
    comfy = find_comfyui(cfg["comfyui_root"])
    with Flash(config=config) as flash:
        functions = []
        for tone in flash.tone_list():
            info = flash.tone_info(tone["tone"])
            functions.append({
                **tone,
                "ready": info["models_ready"],
                "missing": [model["path"] for model in info["models"] if not model["exists"]],
            })
    available = [entry for entry in functions if entry["ready"]]
    if not available:
        return {"ok": False, "code": "MISSING_MODELS", "config": str(config), "functions": functions,
                "message": "缺少模型。按各功能的 missing 清单核对 config 中的目录。"}

    python = choose_python(comfy, args.python or cfg.get("python"))
    if args.python:
        settings = read_json(config)
        if settings.get("python") != str(python):
            settings["python"] = str(python)
            write_text(config, json_text(settings))
    argv = [str(python), "-B", str(ENTRY), "play", "--config", str(config)]
    if skill:
        skill = project_skill(args)
        exclude_skill_from_git(args.project.expanduser().resolve(), skill)
        source = GUIDE.read_text(encoding="utf-8")
        skill_text = source.rstrip() + "\n\n" + MANAGED + "\n\n"
        skill_text += "## 本项目调用配置\n\n"
        skill_text += "把下列数组作为执行参数，在末尾追加 `--request` 和请求 JSON 的绝对路径。\n\n"
        skill_text += "```json\n" + json_text(argv) + "```\n"
        if not skill.exists() or skill.read_text(encoding="utf-8") != skill_text:
            write_text(skill, skill_text)

    names = "、".join(f"{item['tone']} {item['name']}" for item in available)
    return {
        "ok": True,
        "scope": "project" if skill else "conversation",
        "summary": f"已注册功能 — {names}",
        "functions": functions,
        "config": str(config),
        "play_argv": argv,
        "guide": str(skill or GUIDE),
    }


def play(args):
    request = read_json(args.request.expanduser())
    with Flash(config=args.config) as flash:
        return flash.play(**request)


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    cli = argparse.ArgumentParser(description=__doc__)
    actions = cli.add_subparsers(dest="command", required=True)
    setup = actions.add_parser("register", help="检查环境并输出本次注册说明")
    setup.add_argument("--project", type=Path, help="在指定项目中注册技能。省略时用于当前对话")
    setup.add_argument("--agent", choices=tuple(SKILLS), default="codex")
    setup.add_argument("--python", help="推理 Python 的路径")
    setup.add_argument("--comfyui-root", help="设置本机 ComfyUI 目录")
    setup.add_argument("--models-path", help="设置本机模型总目录")
    setup.set_defaults(handler=register)
    render = actions.add_parser("play", help="从 JSON 请求直接生成")
    render.add_argument("--request", type=Path, required=True)
    render.set_defaults(handler=play)
    for action in (setup, render):
        action.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    args = cli.parse_args()
    try:
        result = args.handler(args)
    except (OSError, ValueError, TypeError, subprocess.SubprocessError) as exc:
        result = {"ok": False, "code": "SETUP_OR_REQUEST_ERROR", "message": str(exc)}
    print(json_text(result), end="")
    return 0 if result["ok"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
