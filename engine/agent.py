def local_search_roots():
    roots = [ROOT.parent, Path.cwd(), Path(sys.executable).resolve().parent.parent]
    if os.name == "nt":
        drives = ctypes.windll.kernel32.GetLogicalDrives()
        for index in range(26):
            if drives & (1 << index):
                drive = f"{chr(65 + index)}:/"
                if ctypes.windll.kernel32.GetDriveTypeW(drive) == 3:
                    roots.append(Path(drive))
    return dict.fromkeys(roots)


def read_json(path):
    with path.open(encoding="utf-8-sig") as stream:
        obj = json.load(stream)
    if not isinstance(obj, dict):
        raise ValueError(f"JSON 需要一个对象 | {path}")
    return obj


def json_text(value):
    return json.dumps(value, ensure_ascii=False, indent=2) + "\n"


def write_text(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with NamedTemporaryFile(mode="w", encoding="utf-8", dir=path.parent, delete=False) as stream:
        temp = Path(stream.name)
        stream.write(text)
    try:
        temp.replace(path)
    finally:
        temp.unlink(missing_ok=True)


def find_comfyui(explicit):
    if explicit:
        candidates = [Path(explicit).expanduser().resolve()]
    else:
        candidates = []
        for parent in local_search_roots():
            matching = list(parent.glob("ComfyUI*"))
            candidates.extend([parent, parent / "ComfyUI", *matching])
            candidates.extend(folder / "ComfyUI" for folder in matching)
    found = {p.resolve() for p in candidates if (p / "comfy" / "sd.py").is_file()}
    if len(found) == 1:
        return found.pop()
    if found:
        scores = {root: max(map(model_count, model_roots(root)[:-1])) for root in found}
        top = max(scores.values())
        best = [root for root, score in scores.items() if score == top]
        if top and len(best) == 1:
            return best[0]
        roots = ", ".join(sorted(map(str, found)))
        raise LookupError(f"发现多个 ComfyUI 安装 | {roots}。用 --comfyui-root 指定一个。")
    raise ValueError("找不到 ComfyUI 推理目录。用 --comfyui-root 指向含 comfy/sd.py 的目录。")


def setup_settings(args):
    path = args.config.expanduser().resolve()
    original = read_json(path) if path.is_file() else {}
    settings = dict(original)
    try:
        comfy = find_comfyui(args.comfyui_root or settings.get("comfyui_root") or os.getenv("COMFYUI_ROOT"))
        issue = None
    except (LookupError, ValueError) as exc:
        comfy, issue = None, exc
    if comfy:
        settings["comfyui_root"] = str(comfy)
    override = args.models_path or (not original and os.getenv("COMFYUI_MODELS_PATH"))
    if override:
        base = str(Path(override).expanduser().resolve())
        if base != settings.get("comfyui_models_path"):
            settings.pop("model_dirs", None)
        settings["comfyui_models_path"] = base
    elif not settings.get("comfyui_models_path"):
        settings["comfyui_models_path"] = str(max(model_roots(comfy), key=model_count))
    return path, original, settings, comfy, issue


def model_roots(comfy):
    local = [ROOT / "models"]
    return [comfy / "models", comfy.parent / "H3", comfy.parent / "models", *local] if comfy else local


def model_count(root):
    count = 0
    for name, entry in ARTIFACTS.items():
        path = root / entry["url"].split("/")[-2] / name
        try:
            count += path.stat().st_size == entry["bytes"]
        except OSError:
            continue
    return count


def check_models(settings):
    checked = {}
    problems = {}
    functions = []
    with Flash(config={**settings, "comfyui_root": settings.get("comfyui_root") or str(ROOT)}) as flash:
        for tone in flash.tone_list():
            absent = []
            for model in flash.tone_info(tone["tone"])["models"]:
                path = Path(model["path"]).expanduser().resolve()
                if path not in checked:
                    entry = ARTIFACTS[model["file"]]
                    checked[path] = model_issue(path, entry)
                    if checked[path]:
                        problems[path] = {**entry, "path": str(path), "file": model["file"],
                                          "issue": checked[path], "tones": []}
                if checked[path]:
                    absent.append(str(path))
                    problems[path]["tones"].append(tone["tone"])
            functions.append({**tone, "ready": not absent, "missing": absent})
    return functions, list(problems.values())


def project_skill(args):
    if args.project is None:
        return None
    project = args.project.expanduser().resolve()
    if not project.is_dir():
        raise ValueError(f"找不到项目目录 | {project}")
    path = project / SKILLS[args.agent] / "skills" / "comfyflash" / "SKILL.md"
    if not path.resolve().is_relative_to(project):
        raise ValueError(f"项目技能目录指向项目外 | {path}")
    if path.exists() and MANAGED not in path.read_text(encoding="utf-8-sig").splitlines():
        raise FileExistsError(f"项目已有自定义 ComfyFlash 技能 | {path}")
    return path


def exclude_skill_from_git(project, skill):
    """Keep generated machine paths out of Git without editing tracked files."""
    git = shutil.which("git")
    git_here = any((parent / ".git").exists() for parent in (project, *project.parents))
    if not git:
        if git_here:
            raise ValueError("需要 Git 来保护本机注册文件。当前对话仍可直接注册。")
        return

    def query(*args):
        return subprocess.run(
            [git, "-C", str(project), *args],
            capture_output=True, encoding="utf-8", errors="replace", timeout=10,
        )

    root = query("rev-parse", "--show-toplevel")
    if root.returncode:
        if git_here:
            raise ValueError(f"无法读取目标 Git 仓库 | {project}")
        return

    path = skill.relative_to(project).as_posix()
    if query("check-ignore", "-q", "--", path).returncode == 0:
        return
    if query("ls-files", "--error-unmatch", "--", path).returncode == 0:
        raise ValueError(f"项目已跟踪技能路径，请为本机注册保留未跟踪的技能路径 | {skill}")
    info = query("rev-parse", "--path-format=absolute", "--git-path", "info/exclude")
    info.check_returncode()
    exclude = Path(info.stdout.strip())
    exclude.parent.mkdir(parents=True, exist_ok=True)
    rule = skill.relative_to(Path(root.stdout.strip()).resolve()).as_posix()
    for character in ("[", "*", "?"):
        rule = rule.replace(character, "\\" + character)
    with exclude.open("ab") as stream:
        stream.write(f"\n/{rule}\n".encode("utf-8"))
    if query("check-ignore", "-q", "--", path).returncode:
        raise ValueError(f"项目 Git 规则覆盖了本机忽略设置 | {skill}")


def register(args):
    skill = project_skill(args)
    config, original, settings, comfy, comfy_issue = setup_settings(args)
    functions, missing = check_models(settings)
    runtime = choose_python(comfy, args.python or settings.get("python"))
    if not args.python and settings.get("python") and (
        not runtime["ready"] or not any(gpu["ready"] for gpu in runtime["gpus"])
    ):
        runtime = choose_python(comfy, None)
    hardware = hardware_report(runtime, settings.get("device"), inventory=True)
    environment_ready = bool(comfy and runtime["ready"] and hardware["device"])
    for item in functions:
        item["models_ready"] = item["ready"]
        item["ready"] = item["models_ready"] and environment_ready
    result = {"ok": False, "config": str(config), "functions": functions, "python": runtime,
              "hardware": hardware, "comfyui_root": str(comfy) if comfy else None}
    if missing or not environment_ready:
        needs_cuda_build = hardware["detected_gpu_count"] > 0 and not runtime.get("cuda")
        result.update(
            code="MISSING_MODELS" if environment_ready else "ENVIRONMENT_NOT_READY",
            message="完成报告中的检查项后重新注册。",
            comfyui_issue=str(comfy_issue) if comfy_issue else None, missing_models=missing,
            download_bytes=sum(item["bytes"] for item in missing),
            download_space=download_space(missing), needs_cuda_build=needs_cuda_build,
            needs_path_selection=isinstance(comfy_issue, LookupError),
            needs_download_confirmation=bool(missing or not comfy or not runtime["ready"] or needs_cuda_build),
            install_guide=INSTALL_GUIDE, model_licenses=MODEL_LICENSES if missing else [],
        )
        if missing and not result["needs_path_selection"]:
            result["download_argv"] = [
                sys.executable, "-B", str(ENTRY), "download-models", "--config", str(config),
            ]
            if args.models_path or not settings.get("model_dirs"):
                result["download_argv"].extend(("--models-path", settings["comfyui_models_path"]))
            if comfy:
                result["download_argv"].extend(("--comfyui-root", str(comfy)))
        return result

    python = runtime["path"]
    settings.update(python=python, device=f"cuda:{hardware['device']['index']}")
    verified = hardware["device"].get("video_acceleration", {})
    video_acceleration = {}
    for option in ("sage_attention", "fp16_accumulation"):
        if verified.get(option):
            settings.setdefault(option, True)
        video_acceleration[option] = bool(settings.get(option, False))
    argv = [str(python), "-B", str(ENTRY), "play", "--config", str(config)]
    if skill:
        skill = project_skill(args)
        exclude_skill_from_git(args.project.expanduser().resolve(), skill)
        source = GUIDE.read_text(encoding="utf-8")
        for name in ("h3-video.md", "h3-image.md"):
            relative = f"references/{name}"
            source = source.replace(f"({relative})", f"(<{(GUIDE.parent / relative).as_posix()}>)")
        skill_text = source.rstrip() + "\n\n" + MANAGED + "\n\n"
        skill_text += "## 本项目调用配置\n\n"
        skill_text += "把下列数组作为执行参数，在末尾追加 `--request` 和请求 JSON 的绝对路径。\n\n"
        skill_text += "```json\n" + json_text(argv) + "```\n"
    if settings != original or not config.is_file():
        write_text(config, json_text(settings))
    if skill:
        if not skill.exists() or skill.read_text(encoding="utf-8") != skill_text:
            write_text(skill, skill_text)

    names = "、".join(f"{item['tone']} {item['name']}" for item in functions)
    scope = "项目和当前对话" if skill else "当前对话"
    return {
        **result, "ok": True,
        "scope": "project" if skill else "conversation",
        "summary": f"已注册功能 — {names}",
        "default_engine": f"除非你指定其他工具，{scope}的生图、视频生成和图片编辑默认使用 ComfyFlash。",
        "local_render": LOCAL_RENDER,
        "video_acceleration": video_acceleration,
        "play_argv": argv,
        "guide": str(skill or GUIDE),
    }


def download_models(args):
    if not args.yes:
        raise ValueError("用户确认后才可下载模型。确认后在报告的 download_argv 末尾追加 --yes。")
    _, _, settings, _, issue = setup_settings(args)
    if isinstance(issue, LookupError) and not args.models_path:
        raise ValueError(str(issue))
    _, missing = check_models(settings)
    downloaded = []
    for entry in missing:
        if download_weight(entry):
            downloaded.append(entry["path"])
    return {"ok": True, "downloaded": downloaded, "message": "运行 register 重新检查并注册。"}


def device_mask(index, inherited):
    if inherited is None:
        return str(index)
    tokens = inherited.split(",")
    if not 0 <= index < len(tokens) or not tokens[index].strip():
        raise ValueError(f"cuda:{index} 不在 CUDA_VISIBLE_DEVICES 允许的范围内")
    return tokens[index].strip()


def render_requests(config, requests, report=None):
    with Flash(config=config) as flash:
        results = []
        for position, request in enumerate(requests):
            try:
                result = flash.play(**request)
            except TypeError as exc:
                result = {"ok": False, "error": {"code": "BAD_REQUEST", "message": str(exc)}}
            results.append(result)
            if report:
                report(position, result)
                if host_buffer_error(result.get("error", {}).get("message", "")):
                    break
        return results


def report_worker_result(position, result):
    print(json.dumps({"position": position, "result": result}, ensure_ascii=False), flush=True)


def host_buffer_error(message):
    message = message.lower()
    return any(word in message for word in (
        "hostbuffer.read_file_slice failed", "hostbuffer.truncate failed",
    ))


def worker_memory_error(message):
    message = message.lower()
    return host_buffer_error(message) or "out of memory" in message or "cudaerrormemoryallocation" in message


def worker_results(args, requests, index, *, safe_memory=False):
    paths = [str(path.expanduser().resolve()) for _, path in requests]
    environment = os.environ.copy()
    environment["CUDA_VISIBLE_DEVICES"] = device_mask(index, environment.get("CUDA_VISIBLE_DEVICES"))
    command = [sys.executable, "-B", str(ENTRY), "play", "--config", str(args.config), "--worker"]
    if safe_memory:
        command.append("--safe-memory")
    for path in paths:
        command.extend(("--request", path))
    results = []
    try:
        run = subprocess.run(command, env=environment, capture_output=True, encoding="utf-8", errors="replace")
        diagnostics = run.stderr.strip().splitlines()
        for line in run.stdout.splitlines():
            try:
                report = json.loads(line)
            except ValueError:
                diagnostics.append(line)
                continue
            if not isinstance(report, dict) or report.get("position") != len(results):
                diagnostics.append(line)
                continue
            item = report.get("result")
            if isinstance(item, dict) and isinstance(item.get("ok"), bool) and len(results) < len(paths):
                results.append(item)
        reported_errors = [result.get("error", {}).get("message", "") for result in results]
        diagnostics = [line for line in reported_errors + diagnostics if line.strip()]
        memory_error = next((line for line in diagnostics if host_buffer_error(line)), None)
        if memory_error is None:
            memory_error = next((line for line in diagnostics if worker_memory_error(line)), None)
        failure = memory_error or (diagnostics[-1] if diagnostics else f"进程退出码 {run.returncode}")
        error_code = "WORKER_MEMORY_ERROR" if memory_error else "WORKER_ERROR"
    except OSError as exc:
        failure, error_code = str(exc), "WORKER_ERROR"
    results.extend({"ok": False, "error": {"code": error_code, "message": failure}} for _ in paths[len(results):])
    return [(position, {**result, "device": f"cuda:{index}"})
            for (position, _), result in zip(requests, results)]


def most_free_device(hardware):
    usable = (gpu for gpu in hardware["gpus"] if gpu["ready"])
    return max(usable, key=lambda gpu: (gpu["free_mib"], gpu["total_mib"]), default=None)


def batch_result(results, devices):
    return {"ok": all(result["ok"] for result in results), "parallel": len(devices) > 1,
            "devices": [f"cuda:{index}" for index in devices], "results": results}


def play(args):
    paths = args.request if isinstance(args.request, list) else [args.request]
    requests = [read_json(path.expanduser()) for path in paths]
    if getattr(args, "worker", False):
        config = load_config(args.config)
        if args.safe_memory:
            config.update(disable_pinned_memory=True, disable_comfy_compiler=True)
        elif sys.platform == "win32" and config.get("dynamic_vram", True):
            # Separate GPU workers still compete for the same pinned host memory.
            config.setdefault("disable_pinned_memory", True)
        results = render_requests(config, requests, report_worker_result)
        return batch_result(results, [])
    if len(requests) == 1:
        device = load_config(args.config).get("device", "cuda:0")
        inherited = os.getenv("CUDA_VISIBLE_DEVICES")
        if device.startswith("cuda:") and inherited and "," in inherited:
            os.environ["CUDA_VISIBLE_DEVICES"] = device_mask(int(device.split(":")[1]), inherited)
        return render_requests(args.config, requests)[0]
    outputs = [Path(request["output"]).expanduser().resolve() for request in requests if request.get("output")]
    if len(outputs) != len(requests) or len(set(outputs)) != len(outputs):
        raise ValueError("批量请求必须各有一个不同的 output 路径。")
    cfg = load_config(args.config)
    preferred = cfg.get("device", "cuda:0")
    if preferred == "cpu":
        return batch_result(render_requests(args.config, requests), [])
    hardware = hardware_report(probe_python(sys.executable, hardware_only=True), preferred)
    devices = hardware["active_devices"]
    if len(devices) < 2:
        best = most_free_device(hardware)
        if best is None:
            raise ValueError(hardware["summary"])
        devices = [best["index"]]
    devices = devices[:len(requests)]
    indexed = list(enumerate(paths))
    with ThreadPoolExecutor(max_workers=len(devices)) as executor:
        workers = [executor.submit(worker_results, args, indexed[slot::len(devices)], index)
                   for slot, index in enumerate(devices)]
        finished = dict(item for worker in workers for item in worker.result())
    serial_retries = 0
    safe_memory = False
    retry = []
    for position, output in finished.items():
        error = output.get("error", {})
        message = error.get("message", "")
        if host_buffer_error(message):
            safe_memory = True
            retry.append((position, paths[position]))
        elif len(devices) > 1 and (error.get("code") in {"OOM", "WORKER_MEMORY_ERROR"} or worker_memory_error(message)):
            retry.append((position, paths[position]))
    if retry:
        refreshed = hardware_report(probe_python(sys.executable, hardware_only=True), preferred)
        available = most_free_device(refreshed)
        if available is not None:
            finished.update(worker_results(args, sorted(retry), available["index"], safe_memory=safe_memory))
            serial_retries = len(retry)
    result = batch_result([finished[position] for position in range(len(paths))], devices)
    if serial_retries:
        result["serial_retries"] = serial_retries
    return result


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    cli = argparse.ArgumentParser(description=__doc__)
    actions = cli.add_subparsers(dest="command", required=True)
    setup = actions.add_parser("register", help="检查环境并输出本次注册说明")
    setup.add_argument("--project", type=Path, help="在指定项目中注册技能。省略时用于当前对话")
    setup.add_argument("--agent", choices=tuple(SKILLS), default="codex")
    setup.add_argument("--python", help="推理 Python 的路径")
    setup.add_argument("--comfyui-root", help="设置本机 ComfyUI 目录")
    setup.add_argument("--models-path", help="设置本机模型总目录")
    setup.set_defaults(handler=register)
    download = actions.add_parser("download-models", help="得到用户确认后补齐官方权重")
    download.add_argument("--yes", action="store_true", help="表示用户已经确认下载")
    download.add_argument("--comfyui-root")
    download.add_argument("--models-path")
    download.set_defaults(handler=download_models)
    render = actions.add_parser("play", help="从 JSON 请求直接生成")
    render.add_argument("--request", type=Path, action="append", required=True, help="可重复传入多个请求")
    render.add_argument("--worker", action="store_true", help=argparse.SUPPRESS)
    render.add_argument("--safe-memory", action="store_true", help=argparse.SUPPRESS)
    render.set_defaults(handler=play)
    for action in (setup, download, render):
        action.add_argument("--config", type=Path, default=DEFAULT_CONFIG)
    args = cli.parse_args()
    try:
        result = args.handler(args)
    except (OSError, ValueError, TypeError, subprocess.SubprocessError) as exc:
        result = {"ok": False, "code": "SETUP_OR_REQUEST_ERROR", "message": str(exc)}
    if not getattr(args, "worker", False) or result.get("code") == "SETUP_OR_REQUEST_ERROR":
        print(json_text(result), end="")
    return 0 if result["ok"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
